namespace HexLive.Simulation.Runtime
{

/// <summary>
/// §156: спящие чанки — размер решётки и радиус пробуждения.
/// </summary>
public static class ChunkBalance
{
    // ─────────────────────────────────────────────────────────────
    // ⭐ ГЛАВНЫЙ ВЫКЛЮЧАТЕЛЬ. false = мир ведёт себя ровно как до §156:
    // IsAwake всегда true, окно догона всегда равно одному slow-такту, порядок
    // обхода прежний — то есть бит-в-бит, что и сторожит golden_trace.
    // Включение меняет порядок float-операций и принимается отдельным коммитом
    // с пересъёмом эталонов (§156.6, прецедент §135.5).
    public static bool ChunkSleepEnabled = false;

    // Сторона чанка в тайлах. 8 = 64 тайла: достаточно крупно, чтобы карта
    // чанков и активный набор были копеечными, и достаточно мелко, чтобы
    // радиус пробуждения (~18) не будил остров целиком.
    public static int ChunkSizeTiles = 8;

    // Пол радиуса пробуждения. Обязан быть НЕ МЕНЬШЕ самого дальнего
    // взаимодействия, не выражаемого через зоркость: смертный крик о помощи
    // §57 слышно за 10 гексов, материализация зверя §147.3 — 8.
    public static int MinWakeRadiusTiles = 10;

    // Запас поверх радиуса: NPC пересекает границу чанка не мгновенно, а
    // активный набор пересчитывается раз в тик.
    public static int WakeRadiusMarginTiles = 2;
}

}
