namespace HexLive.Simulation.Runtime
{

// Spec §105: УМИРАНИЕ вместо мгновенной смерти. До сих пор смерть наступала в
// один тик — грудь разбита, кровь на нуле, голод доел последнюю зону — и тело
// уезжало в Corpses тем же проходом. Никто не успевал ничего сделать, даже
// стоя рядом с бинтом в руках.
//
// Теперь между «должна умереть» и «умерла» есть ОКНО: тело падает, лежит и
// тает. Тает не сам стат — он уже на нуле — а отдельный ЗАПАС (DyingReserve,
// 1 → 0), который и есть «отрицательная часть» шкалы. Скрытый запас выбран
// осознанно: Blood/Hunger/Thirst читают больше тридцати систем как 0..1, и
// настоящий минус пришлось бы протаскивать через каждый Clamp01 и каждую
// формулу — а запас живёт в одном месте и виден игроку чипом Dying.
//
// ⭐ DyingEnabled = false восстанавливает доигровое поведение ПОБИТОВО: ни одна
// точка входа не отклоняется, смерть снова мгновенная. Это выключатель для
// бисекции соаком (паттерн Spec53.Enabled / Spec76.AttributeSpread = 0).
//
// Голова — намеренное исключение: разбитая в ноль голова убивает сразу, как и
// раньше. В игре должен остаться хотя бы один мгновенный исход, иначе любая
// смерть превращается в отложенную сцену.
public static class Spec105
{
    public static bool DyingEnabled = true;

    // ---- Окно умирания ------------------------------------------------------

    // Сколько ТИКОВ полный запас (1.0) тает до нуля, по причинам. Запас
    // считается по фактически прошедшим тикам, а не по числу вызовов, поэтому
    // цифры не зависят от TickLayer и от того, на каком слое крутится тик.
    //
    // Порядок величин: помощнице нужно решить (аукцион), дойти (сотня-другая
    // тиков) и отработать AidDuration = 70. Меньше ~600 — спасение физически
    // недостижимо, и окно превращается в косметику.
    public static int WindowTicksBloodLoss = 900;   // кровь вытекла — самый быстрый исход
    public static int WindowTicksTorso = 1200;      // грудь пробита
    public static int WindowTicksStarvation = 1800; // голод: тело сдаётся медленно
    public static int WindowTicksDehydration = 1500;

    // §76: сколько окна покупает характеристика. Форма как у всех остальных
    // множителей — `1 + (attr − Mean) × Gain`, то есть при Spread 0.5 и Gain
    // 0.3 это ±15%. Стойкость держит кровь и грудь, Неприхотливость — голод и
    // жажду («она может дольше не есть и не пить» — та же ось).
    public static float HoldGain = 0.3f;

    // Урон по лежащей срезает запас напрямую: волк догрызает. Множитель на
    // ЗАШЕДШИЙ урон (после брони и §76), так что удар в 0.2 HP снимает 0.3
    // запаса — примерно треть окна за укус, и стая добивает за три-четыре.
    public static float DamageReserveFactor = 1.5f;

    // Пока помощница РАБОТАЕТ над ней, запас не тает: доиграть перевязку она
    // успевает всегда, а «умерла на последнем тике бинтования» читалось бы как
    // издевательство, а не как драма.
    public static bool AidFreezesReserve = true;

    // ---- Пол тела -----------------------------------------------------------

    // Витальные зоны умирающей пиннятся НА ЭТОТ пол вместо нуля.
    //
    // ⭐ Это не поблажка, а несущая конструкция. «Мертва» в этом проекте —
    // структурное свойство (переезд в Entities.Corpses), но около сорока мест
    // читают `Health <= 0f` как «труп»: бой, рейд, хищники, мечты, опасности.
    // Умирающая обязана оставаться ЖИВОЙ для всех них — иначе её перестанут
    // видеть ровно те системы, которые должны над ней склониться. Пол держит
    // Health строго положительным, и ни одну из тех проверок не надо трогать.
    public static float BodyFloor = 0.02f;

    // ---- Выход --------------------------------------------------------------

    // Кровопотеря отпускает, когда кровотечение остановлено И крови набралось
    // хоть сколько-то выше этого. Ровно то, что делает одна перевязка
    // (StabilizeBleedingOnAidStart закрывает окно свежей раны, TreatBlood
    // доливает 0.2) — и то, к чему организм приходит сам, если рана
    // заклоттилась, а она сыта.
    public static float BloodExitFloor = 0.05f;

    // ---- Спасение (§53) -----------------------------------------------------

    // Надбавка к ставке помощи на умирающую. Полный StarvingBoost: спасение
    // обгоняет любую работу и любую другую помощь, но НЕ обгоняет собственный
    // кризис помощницы — этот гейт §53.5 остаётся нетронутым.
    public static float RescueEmergencyBoost = 1f;

    // ---- Штраф после спасения (эффект Convalescent) -------------------------

    // «Едва живая»: несколько игровых часов она еле функционирует. Сутки —
    // DayLengthTicks 24000 (§19.7B: это ВИЗУАЛЬНЫЕ часы), то есть час ≈ 1000
    // тиков; 3600 — примерно три с половиной часа.
    public static int ConvalescentTicks = 3600;

    // Выносливость восстанавливается втрое медленнее, тратится вдвое быстрее,
    // ходит вдвое медленнее — ровно то, что просили: «ходит такой грустный».
    public static float ConvalescentStaminaRegenFactor = 1f / 3f;
    public static float ConvalescentStaminaDrainFactor = 2f;
    public static float ConvalescentMoveFactor = 0.5f;
}

}
