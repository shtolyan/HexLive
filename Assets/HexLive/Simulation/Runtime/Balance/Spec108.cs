namespace HexLive.Simulation.Runtime
{

// §108: групповая охота. Трое собрались поболтать — и разговор сворачивает на
// чужака (§81). Если ЕГО ненавидят ВСЕ, кто стоит рядом, болтовня становится
// сговором: они бросают дела и идут бить его вместе.
//
// Механика намеренно собрана из уже работающих кусков: пакт — это прерывание
// §57/§72/§81 (аукцион для срочного не работает, проверено дважды), сам бой —
// «N ударов на одну цель» из RaidSystem.PullDefenders, а «не убить, а побить»
// обеспечивает милость §86 — порог ненависти пакта (-0.5) НАМЕРЕННО выше
// порога Spec86.HatredAffinity (-0.6), за которым удары начинают убивать.
public static class Spec108
{
    // Один выключатель на весь слой: false — тема «чужак» исчезает из
    // розыгрыша, пакт не заключается, система охоты выходит на первой строке.
    public static bool GroupHuntEnabled = true;

    // Сколько подруг должно СТОЯТЬ РЯДОМ, чтобы разговор мог свернуть на него.
    // Двое — это просто разговор; сговор начинается с троих.
    public static int GroupHuntMinGirls = 3;

    // В каком радиусе от собеседницы считаются «собравшиеся» — кружок у костра,
    // а не «все, кто на этом краю острова». Замерено: на 2 гексах механика
    // живёт только на тесной арене §91, а в настоящем мире трое НИ РАЗУ не
    // оказались так близко за 10 дней на трёх сидах (ноль пактов). На 4 —
    // 1-2 сговора за те же 10 дней на каждом сиде.
    public static int GroupHuntGatherRadiusTiles = 4;

    // Порог ненависти, при котором она готова идти его бить. Affinity
    // ∈ [-1..+1], одна сцена абьюза даёт -0.35 — значит, двух сцен хватает.
    public static float GroupHuntHateThreshold = -0.5f;

    // Базовый вес темы «чужак» в розыгрыше (у SmallTalk 1.00).
    public static float GroupHuntTopicWeight = 1.2f;

    // Сколько добавляет ненависть: чем сильнее его ненавидят, тем чаще о нём
    // и говорят.
    public static float GroupHuntTopicHateGain = 1.5f;

    // Дальше этого сговариваться не о чем — идти полострова за местью они не
    // станут. По умолчанию покрывает почти весь остров.
    public static int GroupHuntMaxPactDistanceTiles = 40;

    // Замок цели = весь бюджет охоты. Истёк — охота провалилась, все
    // расходятся. 900 тиков ≈ 3.75 минуты мира при 4 Гц.
    public static int GroupHuntLockTicks = 900;

    // Насколько передняя охотница может оторваться от САМОЙ ОТСТАВШЕЙ, прежде
    // чем встанет и подождёт. Это и есть «держатся вместе»: сравнение идёт с
    // хвостом группы, поэтому отстающая не ждёт никогда и клинч невозможен.
    public static int GroupHuntSpreadTiles = 2;

    // Здоровье, ниже которого он уже не принимает бой один на один и бежит.
    // Высокое нарочно: трое против одного — он должен побежать, а не героически
    // умирать, и вся сцена превращается в погоню, а не в казнь.
    public static float GroupHuntTargetFleeHealth = 0.85f;

    // ⭐ Здоровье, ниже которого ОХОТНИЦА выходит из расправы и убегает. Пара к
    // порогу выше: право убежать нужно обеим сторонам. Без него расправа шла до
    // последней — он вооружён и вдвое сильнее каждой, и первая же дошедшая до
    // него тройка ложилась целиком (сид 42: колония 4→1 за 700 тиков).
    // Числа те же, что у жертвы налёта (Spec72.RaidVictimFleeHealth и порог
    // худшей части): бить и получать по голове — одно и то же ремесло.
    public static float GroupHuntHunterFleeHealth = 0.6f;

    public static float GroupHuntHunterFleeWorstPart = 0.35f;

    // Меньше этого числа охотниц на ногах — охота разваливается.
    public static int GroupHuntMinRemaining = 2;

    // Передышка после охоты (любой). Без неё они бы шли на него снова тем же
    // вечером, как только тема выпадет повторно.
    public static int GroupHuntCooldownTicks = 3000;

    // Сколько стресса снимает удавшаяся расправа. Отомстили — отпустило.
    public static float GroupHuntStressRelief = 0.25f;

    // Насколько теплеют друг к другу те, кто ходил вместе. Общее дело роднит.
    public static float GroupHuntBondAffinity = 0.10f;

    // ⭐ Сколько симпатии теряет ТА, КТО ВИДЕЛА сцену (не жертва). Недостающее
    // звено всей механики: без него он фиксируется на удобной жертве, её
    // симпатия уходит в -1.00, а у двух других остаётся -0.35, и единогласия
    // не бывает никогда. Меньше, чем теряет жертва (0.35): видеть — не то же,
    // что пережить.
    public static float GroupHuntWitnessAffinityLoss = 0.18f;

    // В каком радиусе сцену «видно». Шире круга сговора: слышно и с соседнего
    // гекса, а прятать это от подруг он не умеет.
    public static int GroupHuntWitnessRadiusTiles = 5;

    // Сколько ударов группы значит «проучили». Считается по всей группе за
    // одну охоту; когда счёт набран и он оторвался или побежал — расправа
    // удалась. Без этой меры у охоты с пощадой нет успешного конца вовсе.
    public static int GroupHuntBlowsToRout = 6;

    // Держать ли пощаду §86 на время расправы, независимо от ненависти.
    //
    // ВЫКЛЮЧЕНО намеренно: исход решает лестница ненависти, а не эта ручка.
    // Кто дошла до -0.6 — добьёт, кто не дошла — отобьёт и отстанет, и в одной
    // и той же охоте это решает каждая за себя. Так расправа перестаёт быть
    // сценой с заранее известным концом. Цена известна и принята: чужак на
    // острове один, и иногда линия §81 кончается вместе с ним (замерено: 2
    // охоты из 4 доводили до смерти на четвёртый-пятый день).
    //
    // Включить — они бьют строго до «свалился», и он всегда встаёт.
    public static bool GroupHuntMercyHolds = false;

    // Насколько он их за это возненавидит (в свою сторону отношений). Это его
    // лестница оружия §91: побитый чужак в следующий раз возьмётся за нож.
    public static float GroupHuntTargetGrudge = 0.30f;
}

}
