namespace HexLive.Simulation.Runtime
{

// §111: обобрать беспомощного врага. Увидел лежащего врага, который точно не
// ответит (кома §60, умирание §105, обморок §40.13), — бросил всё, подошёл и
// обчистил: по одной вещи, оружие первым.
//
// Ниша была пуста нарочно и с двух сторон: §81 отсеивает беспомощную ДО
// скоринга («она взвесила силы и сдалась» требует, чтобы она была в сознании),
// а §28.15F умеет только мёртвых. Между ними лежала целая механика: живая, но
// выключенная, с ножом в кармане, — и никто её не трогал.
//
// Спящих и плачущих §110 эта механика НЕ трогает: обе в сознании и обе могут
// среагировать, а тихий грабёж спящей — это кража §40.5.
public static class Spec111
{
    // Один выключатель на весь слой: false — поведение как до §111 (ставка
    // всегда ноль, BestMark не зовётся). В ТРАССЕ строка GoalScored остаётся:
    // цель объявлена и участвует в аукционе с нулём, как всякая недоступная.
    public static bool LootHelplessEnabled = true;

    // Базовая ставка. Складывается в 0.95 (AddGoalScore кладёт свои 0.1) —
    // выше скорби (0.7) и быта, ниже аварийных нужд с их EmergencyBoost.
    // «Не лутать, когда сам в бою/в коме/бежит» ставить сюда не нужно: в этих
    // трёх состояниях аукцион закрыт целиком, ещё до скоринга.
    public static float LootHelplessBaseScore = 0.85f;

    // Прибавка, когда у лежащего оружие МОЩНЕЕ его собственного
    // (GearCatalog.AddsValueOver). Это и есть «защита» в мотиве: мачете §79
    // нельзя скрафтить, и до §111 оно попадало в колонию только с трупа.
    public static float LootHelplessWeaponBonus = 0.30f;

    // В каком радиусе он вообще замечает лежащего. Шесть — ровно как у §81:
    // мы режем ЗНАНИЕ, а не только дорогу, иначе он «чует» тело через полострова.
    public static int LootHelplessSightRadiusTiles = 6;

    // Тиков на одну вещь. Вдвое быстрее лута трупа (20): там раздевание, тут
    // «хоп-хоп» по карманам. Обмороки коротки (80 тиков), и этот темп —
    // единственное, что успевает снять с жертвы больше одной вещи.
    public static int LootHelplessTakeTicks = 10;

    // Передышка после СЫГРАННОЙ сцены — чтобы он не садился на то же тело
    // сразу, как только у неё заведётся вторая вещь.
    public static int LootHelplessCooldownTicks = 600;

    // Передышка после СРЫВА (очнулась, умерла, не влезло). Короткая: срыв —
    // не попытка. Ровно Spec81.AbuseRetryTicks, и по той же причине.
    public static int LootHelplessRetryTicks = 40;

    // Потолок сцены — страховка от зависшего такта, а не игровой срок.
    public static int LootHelplessMaxSceneTicks = 240;
}

}
