namespace HexLive.Simulation.Runtime
{

// §121: ручное управление персонажем. Игрок берёт одного NPC под себя — и её
// автономия ВЫКЛЮЧАЕТСЯ целиком: аукцион целей, страхи, приглашения и
// планировщик её больше не трогают, исполняются только приказы из очереди
// команд (SimulationCommandQueue → ManualCommandExecutor).
//
// Правило боя §121.2: атакованный ручной персонаж ВСЕГДА бросает приказ и
// отвечает. Правило Кенши («с приказом терпит») отменено игроком — «идёт и
// терпит побои» читалось как поломка, а не приём.
//
// ⭐ Каждая ветка ручного режима стоит и под этим выключателем, и под
// npc.Mind.ManualControl. Мир без единого ручного NPC обязан считаться
// БАЙТ В БАЙТ так же, как до §121 (golden_trace.sh — критерий приёмки):
// порядок float-операций здесь и есть поведение.
public static class Spec121
{
    // Один выключатель на весь слой: false — поведение как до §121, команды
    // не применяются, все карв-ауты в боевых системах спят.
    public static bool ManualControlEnabled = true;

    // Сколько тиков держится резервация узла, взятая приказом. Ровно столько
    // же берёт планировщик под свои подходы — приказ не привилегированнее
    // обычного плана, он просто приходит от игрока.
    //
    // Дистанция «встать рядом» сюда НЕ вынесена намеренно: её считает
    // SpatialQueries.BesideReach из радиуса самого объекта, и вторая ручка
    // рядом означала бы, что к пальме можно подойти двумя разными способами.
    public const int ManualReserveTicks = 48;

    // §121.7: столько тиков ручная стоит с завершённым приказом без единой
    // команды, прежде чем автоматически вернётся под ИИ (~5 минут при 4 Гц).
    // Окно перезапускают принятая команда И завершение приказа; отклонённая
    // команда — нет.
    public const int ManualIdleReleaseTicks = 1200;
}

}
