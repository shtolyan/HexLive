namespace HexLive.Simulation.Runtime
{

// §129: дверь открывают руки. Закрытая дверь — ПОВЕДЕНИЕ, не топология:
// портал хижины никогда не Blocked, общий граф связности всегда видит
// интерьер достижимым (для своих это правда — она подойдёт и откроет).
// Чужой фракции закрытые чужие порталы выдаются роутеру жёстким запретом
// (hardAvoid, прецедент — MobForbiddenJunctions), а «дотянуться руками»
// сквозь закрытую створку нельзя никому (SpatialQueries.IsBarrierFor).
//
// ⭐ Хижина спавнится в КАЖДОМ мире (SpawnCompletedTestHut — дефолт), так что
// включённый §129 сдвигает golden trace на всех сидах — это задекларировано
// в спеке. Критерий приёмки выключателя как у §121: Enabled=false обязан
// давать БАЙТ В БАЙТ трейсы до-§129 — двери никто не трогает, все наборы
// пусты, ни одной новой float-операции на маршруте.
public static class Spec129
{
    // Один выключатель на весь слой: false — NPC не открывают и не закрывают
    // дверей, дверь стоит как стояла (по умолчанию открытой).
    public static bool Enabled = true;

    // Пауза «распахнуть створку» перед шагом в проём: 2 тика на 4 Гц,
    // покрывает анимацию петли HutDoorVisual (0.32 с) с тактом запаса.
    // Едет в Movement.ClimbPauseTimer — намеренно НЕ сейвится (прецедент:
    // пауза входа в воду), после загрузки гейт просто сработает заново.
    public static float DoorSwingSeconds = 0.5f;

    // Закрывать ли за собой. Отдельно от Enabled: мир с открывающими, но не
    // закрывающими дверьми — легальная диагностическая конфигурация.
    public static bool CloseBehind = true;

    // Сколько ближайших шагов чужого маршрута смотрит закрывающая: если у
    // союзницы портал в этом окне пути — не хлопать дверью ей в нос.
    public static int CloseBehindLookaheadSteps = 2;
}

}
