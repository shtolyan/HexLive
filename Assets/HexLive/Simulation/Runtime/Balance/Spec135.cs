namespace HexLive.Simulation.Runtime
{

// Spec §135: волк уносит добычу. Оторванная в бою конечность (§50) — это еда,
// а не декорация: зверь берёт её в зубы, БРОСАЕТ бой, отходит за пределы своей
// зоны агра, там стоит с ногой в пасти, доедает — и после этого полдня не
// нападает ни на кого. Так укус, стоивший колонистке ноги, перестаёт быть
// началом бесконечной травли и становится концом сцены.
public static class Spec135
{
    // Один выключатель на весь слой: false — конечность падает на землю, как
    // и раньше (§50.4), зверь продолжает драку.
    public static bool Enabled = true;

    // Насколько ДАЛЬШЕ своего радиуса агра зверь утаскивает добычу, в гексах.
    // Смысл ровно один: встав, он не должен снова видеть колонию как цель —
    // иначе «ушёл поесть» читается как «отбежал и вернулся».
    public static int RetreatMarginTiles = 3;

    // Предохранитель отхода. Остров маленький, а лагерь бывает разбит поперёк
    // единственного прохода: зверю может быть некуда уйти. После этого срока
    // он ест там, где стоит, — иначе конечность висела бы в зубах вечно.
    public static int RetreatGiveUpTicks = 400;

    // Сколько зверь стоит с добычей в зубах, прежде чем она исчезнет.
    // 1200 тиков = 5 реальных минут на 4 Гц — сцену видно, но она не вечна.
    public static int EatTicks = 1200;

    // Чутьё на падаль: насколько ДАЛЬШЕ зоны агра зверь замечает лежащую
    // конечность. Нос длиннее глаз, но не бесконечен — за ногой через весь
    // остров он не побежит.
    public static int ScentRadiusBonusTiles = 2;

    // Сколько тиков зверь не смотрит на падаль после неудачного похода за ней
    // (дороги нет). Без этого он каждый средний тик заново строил бы путь к
    // недостижимой ноге — ровно та цена, которой здесь быть не должно.
    public static int ScentGiveUpTicks = 300;

    // Сытость: сколько тиков после еды зверь вообще не наводится на добычу.
    // 12000 = половина визуальных суток (§19.7B, DayLengthTicks = 24000) —
    // то самое «полдня», о котором просил игрок.
    public static int SatedTicks = 12000;
}

}
