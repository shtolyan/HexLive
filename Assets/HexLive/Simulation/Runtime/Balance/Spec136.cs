namespace HexLive.Simulation.Runtime
{

// Spec §136: дневник колонистки. У игрока есть общеколониальная лента (§30.17,
// «хроника»), которая отвечает на вопрос «что произошло в колонии». Она не
// отвечает на вопрос «что пережила вот эта девушка»: события в ней сухие,
// безличные и перемешаны между всеми.
//
// Дневник — это личная выжимка той же хроники: раз в игровой час каждая NPC
// оставляет ОДНУ запись о самом важном, что с ней случилось. Симуляция хранит
// только ЧТО записано (тип события, настроение, о ком речь) — сама фраза
// собирается на стороне вида из терминов I2 (§58), поэтому дневник переключает
// язык на лету и в C# нет ни одной строки текста.
public static class Spec136
{
    // Один выключатель на весь слой: false — записи не копятся и не пишутся,
    // кольца остаются пустыми. Мир от этого не меняется ничем (см. ниже).
    public static bool Enabled = true;

    // Ёмкость кольца записей на одну NPC. 48 = двое визуальных суток при
    // одной записи в час (§19.7B: DayLengthTicks = 24000, час = 1000 тиков).
    // Старое вытесняется молча — дневник это память, а не архив.
    public static int Capacity = 48;

    // Длина «часа» в тиках. Ровно 1/24 визуальных суток; вынесено сюда, а не
    // посчитано на месте, чтобы растяжение суток (§19.7B уже растянуло их в
    // 10 раз) не превращало дневник в спам или в молчание.
    public static int HourTicks = WorldBalance.DayLengthTicks / 24;

    // Граница между «событием» и «бытом». Вес живёт в JournalCatalog; здесь
    // только порог, потому что его хочется двигать, не трогая таблицу.
    //
    // Выше порога — претендует на запись часа (побеждает максимальный вес,
    // поэтому «важное» и «просто заметное» разделяет сама шкала весов).
    // Ниже — в отдельную запись не попадает НИКОГДА, только перечислением
    // внутри тихой: «ничего особенного, валила дерево, грелась у костра».
    //
    // Второго порога здесь сознательно нет. Он был («MajorWeight = 60») и
    // ничего не делал: раз побеждает максимум, «важное перебивает заметное»
    // получается само. Ручка, которая молча не работает, хуже отсутствующей —
    // на ней теряют время, крутя её и не видя эффекта.
    public static int MinorWeight = 20;

    // Сколько бытовых дел перечисляет тихая запись. Три — это «пилила дрова,
    // грелась у костра, ела мясо»; четвёртое уже читается как список задач.
    public static int QuietChoreSlots = 3;

    // Потолок склейки тихих часов в одну запись. Без склейки кольцо на 48
    // забивалось бы сорока восемью «ничего не происходило» за двое спокойных
    // суток, и первая же рана вытеснила бы всё остальное. Потолок нужен, чтобы
    // «тихо» не растянулось на неделю одной строкой и день не потерялся.
    public static int MaxQuietRun = 6;
}

}
