namespace HexLive.Simulation.Runtime
{

/// <summary>
/// §137: «просто отдыхает» — это ПОЗА, а не пустая строка состояния.
///
/// <para>
/// Аукцион целей регулярно выбирает <c>Idle</c> — и до сих пор это значило
/// «стой столбом»: плана у цели нет, взаимодействия нет, вид играет обычный
/// стоячий idle. Игрок видит это чаще любой другой сцены. Теперь незанятая
/// колонистка садится на землю (цепочка клипов <c>RestDown → RestIdle →
/// RestUp</c>) и встаёт, когда появляется дело.
/// </para>
/// <para>
/// ⭐ Здесь намеренно <c>const</c>, а не <c>static</c>-поля — ровно по той же
/// причине, что в <see cref="Spec133"/>: тюнимый ноб обязан иметь зеркало в
/// Unity-ассете и строку в <c>SimData/simdata.json</c> (гейты BalanceParity /
/// SimDataFreshness / BalanceKnobHygiene), а экспорт делается только из
/// редактора. Константа для <c>BalanceReflection.IsTunable</c> невидима, и
/// фича целиком живёт headless.
/// </para>
/// </summary>
public static class Spec137
{
    /// <summary>
    /// Один такт отдыха. Пока он идёт, аукцион для неё закрыт (общее правило
    /// <c>ExecutionStatus.InProgress</c>), поэтому такт КОРОТКИЙ: срочное её
    /// поднимает и так — прерывание проверяется каждый тик, — а такт задаёт
    /// лишь шаг, с которым пересчитывается «а сидеть-то ещё стоит?».
    /// </summary>
    public const int RestBlockTicks = 24;

    /// <summary>
    /// Сколько раз такт перевзводится НА МЕСТЕ, не вставая. Потолок нужен не
    /// ради красоты: без него сидящая не переспрашивает аукцион вовсе, и
    /// появившееся рядом дело она заметит только когда её что-то прервёт.
    /// 9 перевзводов × 24 тика = 240 тиков ≈ минута сидения, потом честный
    /// подъём и новое решение.
    /// </summary>
    public const int MaxRearms = 9;

    /// <summary>
    /// Встав, столько тиков не садится снова. Это и есть «небольшой колдаун,
    /// чтобы сошлось по анимации»: подъём (<c>AiBalance.WakeGraceTicks</c> = 18)
    /// доигрывает в грации, а колдаун поверх него не даёт ей плюхнуться
    /// обратно в тот же миг, когда аукцион снова не нашёл дела.
    /// </summary>
    public const int CooldownTicks = 60;
}

}
