namespace HexLive.Simulation.Runtime
{

/// <summary>
/// §168: быстродействие на сто колонисток.
///
/// <para>
/// Здесь <c>const</c>, как в <see cref="Spec167"/>: константа невидима для
/// BalanceParity/SimDataFreshness и живёт headless без переснятого экспорта.
/// Промоушен в ноб — <c>public static</c> + класс в BalanceClasses + зеркало в
/// конфиг-ассете + переснять simdata.
/// </para>
/// </summary>
public static class Spec168
{
    /// <summary>
    /// §168.6 (а): дальше этого (гекс-дистанция в тайлах) соседка не считается
    /// кандидаткой в собеседницы — ни в скоринге Socialize, ни в BuildTalkPlan.
    /// Радиус восприятия доходит до 16 тайлов, и к партнёрше за полострова
    /// проверка подхода (A* с бюджетом 1500 узлов, до семи станций) почти
    /// всегда упиралась в бюджет: на 103 NPC половина всех поисков пути была
    /// такими «не дойду» за полную цену. Слушательница инициативы §167.7 под
    /// кап не попадает — её выбрал DirectiveMath по своим правилам.
    /// </summary>
    public const int SocializeApproachMaxTiles = 8;

    /// <summary>
    /// §168.6 (а): то же для живой помощи §53 — страдающая дальше этого не
    /// кандидатка ни в ставке Aid/errand, ни в BuildAidPlan. Исключение —
    /// умирающая (<c>IsDying</c>): к ней идут с любого расстояния восприятия.
    /// Шире разговорного капа нарочно: помощь стоит похода, разговор — нет.
    /// </summary>
    public const int AidApproachMaxTiles = 12;
}

}
