namespace HexLive.Simulation.Runtime
{

// §81: абьюз — единственная форма общения, доступная чужаку.
//
// ⭐ Это не «ещё одна злая механика», а закрытие дыры в нуждах. Нужда в общении
// у него не закрывается НИЧЕМ: разговор идёт только между союзниками, амбиентное
// общение §49 считает соседей по фракции, а фракция у него из одного человека.
// Social падает монотонно до нуля и там остаётся. С точки зрения симуляции он
// вечно одинокий — и единственный контакт с людьми, который ему доступен, это
// контакт силой.
//
// Отсюда две развилки одной сцены:
//  * есть что отжать → отжимает (и заодно закрывает голод/жажду);
//  * отжать нечего   → просто гнобит.
// Насыщение общением и порча отношений одинаковы в обоих случаях — потому что
// «удовлетворение» он получает не от добычи, а от того, что его боятся.
public static class Spec81
{
    // Kill-switch. false = мир байт-в-байт догёйтовый.
    public static bool AbuseEnabled = true;

    // --- Когда он вообще идёт абьюзить ---------------------------------------

    // Нужда в общении, ниже которой он идёт искать жертву. Social — это
    // СЫТОСТЬ общением (1 = наговорился), поэтому «низкое» значит одиноко.
    //
    // §104 r6: здесь стояло 0.55, а игра работала на 0.45. Инициализатор
    // ассета/конфига перекрывает этот статик всюду, где есть simdata, — то
    // есть в игре, на сервере и в соаке; вранья не видел никто, пока кто-то не
    // запускал симуляцию БЕЗ экспорта. Истина — OutsiderBalanceConfig, а этот
    // литерал обязан её повторять (следит InitializerParityGate).
    public static float AbuseSocialFloor = 0.45f;

    // Голод/жажда, выше которых он готов отжимать припас.
    public static float AbuseSupplyFloor = 0.55f;

    // Выше этого он уже умирает от голода/жажды — тут не до переговоров, надо
    // жрать всё, до чего дотянется (этим занимается кража §40.5).
    public static float AbuseNeedCeiling = 0.90f;

    // База ставки; к ней прибавляется сила нужды, поэтому голодный и одинокий
    // перебивает свои дела, а сытый и наговорившийся — нет.
    public static float AbuseBaseScore = 0.45f;

    public static int AbuseGraceDays = 2;
    public static int AbuseCooldownTicks = 900;

    // §87: на сколько цель абьюза запирается от аукциона после прерывания.
    // Без замка ближайший же пересчёт вернул бы его к «посидеть»: у одинокого
    // человека досуг стоит дорого, и дорога до жертвы длиннее одного тика.
    public static int AbuseLockTicks = 240;

    // §89: передышка после СОРВАВШЕЙСЯ попытки — короткая. Полный кулдаун за
    // срыв выключал его почти всё время: срывов десятки за прогон.
    public static int AbuseRetryTicks = 40;

    // Сцена отталкивает налёт: ограбил — значит сегодня не убивает.
    public static int AbuseRaidLockoutTicks = 600;

    // --- Выбор жертвы --------------------------------------------------------

    public static int AbuseScanRadiusTiles = 7;

    // §104 r6: здесь была ручка AbuseMaxMarkAllies («сколько подруг рядом он
    // терпит»). Её не читал никто — премису §72 «от группы держится подальше»
    // на деле держит AbuseBreakOffDefenders (он бросает сцену, когда сбегаются)
    // и оценка шансов §101, а не отдельный порог при выборе жертвы.

    // Уважает святилище: у порога дома разворачивается, как волк и как налёт.
    public static bool AbuseRespectsSanctuary = true;

    // --- Расклад сил ---------------------------------------------------------

    // Во сколько раз он должен быть сильнее, чтобы она сдалась.
    public static float AbuseSubmitRatio = 1.2f;

    // Вклад оружия/рук против вклада брони и целости в оценку «кто сильнее».
    public static float AbuseForceOffenseWeight = 0.6f;
    public static float AbuseForceDefenseWeight = 0.4f;

    // Каждая подруга рядом добавляет ей столько же силы в её глазах. Это и есть
    // «она отказала, потому что подошли свои» — без единого частного случая.
    public static float AbuseAllyForceShare = 0.6f;

    // --- Сцена ---------------------------------------------------------------

    // §103: сцена кончается ПО ЧИСЛУ УДАРОВ, а не по секундомеру.
    //
    // «Пять секунд драки» оказалось не тем требованием. Смотреть надо не на
    // часы, а на то, что видно: три замаха, три попадания, разошлись. Сколько
    // это займёт — производная от длины клипа, и подгонять её числом тиков
    // значит каждый раз ломать сцену при смене анимации.
    //
    // Окно (AbuseDurationTicks) осталось СТРАХОВКОЙ на случай, если удары
    // почему-то не ложатся: без него сцена висела бы вечно. Считаем с запасом
    // на три полных цикла удара (замах 1.1 + доигрыш 0.4 + отдых 1.5 ≈ 3 с,
    // то есть 12 тиков) плюс приговор и добыча.
    public static int AbuseDurationTicks = 60;
    // Плач раньше первого удара — иначе такт «она заплакала» не наступает
    // никогда: удар ставит счётчик сразу в 3, и условие AbuseBeat < 1 после
    // этого ложно навсегда. Так оно и было: 2 < 4, и плача не видел никто.
    public static int AbuseBeatCryTicks = 2;
    public static int AbuseBeatBlowTicks = 4;
    // Верхняя граница драки. Приговор наступает РАНЬШЕ — как только легли все
    // назначенные удары; это лишь потолок на случай, если они не ложатся.
    public static int AbuseBeatVerdictTicks = 48;
    // §103: пауза между приговором и тем, как он лезет в её рюкзак.
    public static int AbuseTakeDelayTicks = 4;

    // «Может пару раз ударить». Кулаками, НЕ оружием: ему нужны её припасы и её
    // страх, а не её труп; два удара ножом загнали бы её в порог бегства, и
    // сцена свалилась бы в обычный налёт.
    // §103: три удара — столько сцена и длится. Три в модели, три в анимации.
    public static int AbuseMaxBlows = 3;

    // §99: во сколько ДЛИН КЛИПА разводятся удары сцены. 1.0 — следующий удар
    // ровно после того, как замах доиграл; больше — с паузой между ними.
    // Своя скорость оружия для короткой сцены слишком частая: второй замах
    // перебивал первый, и удара было не видно.
    public static float AbuseBlowSpacing = 1.2f;
    // §93: удар НАСТОЯЩИЙ — такой же, как по зверю. Был множитель 0.35, и
    // урон выходил −0.019: формально попадание, фактически ничего. Теперь
    // говорит само оружие: кулаком слабо, ножом больно, мачете страшно —
    // множителя больше нет вовсе (§104 r6 убрал ручку, которая осталась от той
    // схемы и крутилась в инспекторе, ничего не меняя).
    //
    // От смерти держит не ослабленный урон, а пощада §86: витальную часть
    // ниже порога не опускают, если бьющий не ненавидит.

    // §91: симпатия, ниже которой он берётся за ОРУЖИЕ. Выше — только
    // рукопашка. Нож достаётся не по броску кубика, а по истории отношений:
    // пока она для него прохожая, он машет руками; когда возненавидел — бьёт
    // тем, что в руке. Тот же принцип, что в пощаде §86.
    public static float AbuseWeaponAffinity = -0.5f;

    // §93: насколько глубоко (0..1 от порога до дна) должна зайти ненависть,
    // чтобы он взялся за САМОЕ тяжёлое, что есть в руках. Ниже — берёт что
    // полегче: лёгкая злость не тянется за тесаком.
    public static float AbuseHeavyWeaponDepth = 0.5f;

    // §91: с этой вероятностью она ОГРЫЗАЕТСЯ на тычок — бьёт в ответ. Не
    // выбор «драться или нет» (он решается в приговоре), а рефлекс: получила —
    // ударила. Именно это делает сцену перепалкой, а не избиением столба.
    // §101: ответит ли она — считается, а не бросается монеткой.
    //
    // База умножается на её ШАНСЫ (1/расклад: единица — на равных, 0.2 — он
    // впятеро сильнее), то есть голая девушка против мужика с мачете почти
    // никогда не лезет. Сверху добавляется ЗЛОСТЬ: та, кого он тиранит
    // неделю, огрызается и заведомо проигрывая.
    public static float AbuseFightBackBase = 0.9f;
    public static float AbuseFightBackHatred = 0.5f;

    // §104 r6: здесь была ручка AbuseNoBlowHealthFloor («ниже этого здоровья
    // удар не наносится»). Её не читал никто: умирающую от сцены защищает
    // пощада §86, которая смотрит на отношения и не даёт провалить витальную
    // часть, а не отдельный порог здоровья.

    // Сколько защитниц рядом заставляют его бросить сцену.
    public static int AbuseBreakOffDefenders = 3;

    // --- Последствия ---------------------------------------------------------

    // ⭐ Ради этого всё и затевалось: сцена НАСЫЩАЕТ его общением.
    public static float AbuseSocialGain = 0.35f;

    // Ей от этого не легче: чужой контакт общением не считается.
    public static float AbuseMarkSocialGain = 0f;

    public static float AbuseMarkStressCost = 0.30f;
    public static float AbuseAffinityLoss = 0.35f;
    public static float AbuseTrustLoss = 0.25f;

    // §91: какая ДОЛЯ этой потери симпатии достаётся ему самому. Он теряет
    // меньше — бьют всё-таки её, — но теряет: иначе его собственная неприязнь
    // не растёт, а от неё зависит, возьмётся ли он за нож (§91) и добьёт ли
    // (§86).
    // §93: РОВНО СТОЛЬКО ЖЕ, сколько теряет она. Было 0.5 — и его неприязнь
    // намертво застревала на −0.17: столько же за то же время отыгрывало
    // обратно затухание отношений (NeedsDecaySystem тянет симпатию к нулю).
    // Он презирал её ровно с той скоростью, с какой забывал, — и до порога
    // оружия не добирался НИКОГДА.
    public static float AbuserOwnAffinityShare = 1.0f;

    // Пассивная кража §40.5 намеренно не гейтилась по фракции. Теперь у чужака
    // есть настоящая сцена, и тихий грабёж мимо неё только мешал бы: он молча
    // унёс бы еду, пока идёт её же отжимать.
    public static bool AbuseSupersedesPassiveTheft = true;
}

}
