namespace HexLive.Simulation.Runtime
{

// §82: солнце и злость — две правки, вылезшие из одной игровой сессии.
//
// Солнце убивало забронированного целиком человека за треть дня, а раздетые
// девушки горели весь день и не понимали этого: краснота росла, части тела
// теряли здоровье, а в аукционе это не значило ничего.
//
// Чужак же, наоборот, был неприлично мирным: девушки ходили к нему сами, он
// никого не трогал, сидел с общением в нуле и ничего не хотел.
public static class Spec82
{
    // --- Солнце -------------------------------------------------------------

    // Во что превращается краснота в ставке «одеться». 1.0 значит, что полностью
    // обгоревшая хочет прикрыться так же сильно, как продрогшая.
    public static float SunburnDressWeight = 1.0f;

    // --- Территория ---------------------------------------------------------

    // ⭐ Враждебный NPC в своём лагере запускает сцену выгона §115.
    public static bool TerritorialEnabled = true;

    // Личный радиус зрения; сама граница лагеря берётся из ColonyQueries.InCamp.
    public static int TerritoryRadiusTiles = 5;

    // Пауза между выгонами, чтобы он не молотил одну и ту же без передышки.
    public static int TerritoryCooldownTicks = 300;

    public static float TerritorySubmitHealth = 0.5f;

    public static int TerritoryResponseDelayTicks = 8;

    public static int TerritoryMaxBlows = 3;

    public static float TerritoryBlowSpacingClips = 1.2f;

    public static int TerritoryFightTimeoutTicks = 60;

    // Ставка. Намеренно ОЧЕНЬ высокая: это не дело, которое он выбирает между
    // делами, а реакция на вторжение. Всё, кроме бегства и боя, обязано ждать.
    public static float TerritoryScore = 2.5f;

    // --- Одиночество --------------------------------------------------------

    // Насколько сильнее давит нулевое общение. Ставка абьюза складывается из
    // базы и нужды, а нужда в общении у него ВСЕГДА в нуле — то есть даёт
    // ровно 1.0 и тонет среди бытовых дел. Множитель поднимает её над ними:
    // человеку, который месяц ни с кем не говорил, не до постройки лежанки.
    // §89: одиночество должно перебивать БЫТ, а не только «посидеть». Он ходил
    // купаться, стирать, снова купаться — при общении в нуле. Ставка абьюза =
    // база + одиночество × множитель; при 3.0 полностью одинокий даёт ~3.45, и
    // это выше любой бытовой цели в аукционе.
    public static float LonelinessDriveMult = 3.0f;
}

}
