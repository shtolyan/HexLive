namespace HexLive.Simulation.Runtime
{

// §85: ночь должна быть отдыхом, а не второй сменой.
//
// Соаки показывали ровно одно: главный убийца в мире — не жара и не звери, а
// холодные ночи (Hypothermia 190-644 против Heatstroke 48-248 на прогон). Ночью
// колония бродит, мёрзнет и просыпается голодной, потому что во сне нужды текут
// почти как наяву.
//
// Задумка простая: спящее тело почти ничего не тратит, и единственное, что может
// поднять его среди ночи, — это холод. Тогда «уснуть у костра и подкидывать
// дрова» становится не прихотью, а единственной рабочей стратегией.
public static class Spec85
{
    // Во сколько раз спящее тело медленнее тратит голод и жажду. Было 0.4 —
    // за ночь это съедало заметную долю сытости, и вставали они уже голодными.
    public static float SleepMetabolismFactor = 0.1f;

    // Во сколько раз медленнее уходит нужда в общении во сне. Раньше она текла
    // ПОЛНОСТЬЮ: человек ложился спать сытым и общительным, а вставал одиноким —
    // при том что во сне не с кем и не поговорить.
    public static float SleepSocialFactor = 0.1f;
}

}
