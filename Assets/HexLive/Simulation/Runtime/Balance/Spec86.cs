namespace HexLive.Simulation.Runtime
{

// §86: драка между людьми — не до смерти, если нет ненависти.
//
// Зверь дерётся насмерть, потому что он ест. Человек — почти никогда: он бьёт,
// пока противник не сдался, и уходит. До конца добивают того, кого НЕНАВИДЯТ, и
// это единственное, что должно решать, встанет она после драки или нет.
//
// Отсюда и обратная симметрия: чужак не убивает девушку, которую первый раз
// трясёт, а девушки не добивают его, пока он для них просто неприятный сосед.
// Но если он ходил и тиранил их неделю — симпатия к нему падает с каждой
// сценой (§81), и в какой-то момент они его прикончат. Жестокость становится
// СЛЕДСТВИЕМ истории отношений, а не отдельной ручкой.
public static class Spec86
{
    public static bool MercyEnabled = true;

    // Ниже этой доли здоровья удар человека по человеку не опускает — если
    // бьющий не ненавидит. «Оставить чуть больше половины и уйти довольным».
    public static float MercyHealthFloor = 0.55f;

    // Пощадный удар не опускает ЧАСТЬ под ударом ниже этого. Средний порог
    // выше меряет только среднее по телу и давал одной части «запас» в
    // несколько её максимумов: серия ударов в голову уничтожала жизненно
    // важную часть (VitalDestroyed → мгновенная смерть) задолго до того, как
    // среднее доходило до порога, — и «бой не до смерти» кончался трупом.
    // Пол по части закрывает и это, и отрыв конечности (TrySeverOnBite
    // срабатывает только на части ровно в нуле).
    public static float MercyPartFloor = 0.05f;

    // Потенциально смертельный удар разрешён при
    // Clamp01(-affinity) × (1 - CompassionTrait) >= 0.50.
    public const float KillIntentThreshold = 0.50f;
}

}
