namespace HexLive.Simulation.Runtime
{

// §94: отношения — дело десяти дней, а не одного вечера.
//
// Зашитые числа делали их слишком быстрыми: симпатия упиралась в потолок к
// концу первых суток. А обида, наоборот, таяла быстрее, чем копилась, и это
// был не косметический перекос: неприязнь чужака к жертве застревала около
// −0.17 — ровно столько отыгрывало обратно затухание, — и он НИКОГДА не
// добирался до порога, за которым берётся за нож.
//
// Асимметрия сохранена и осмысленна: обиды забываются быстрее, чем остывает
// дружба. Просто обе скорости стали медленнее и обе стали ручками.
public static class Spec94
{
    // Насколько обида тает к нулю за медленный тик. Быстрее, чем дружба.
    public static float GrudgeDriftPerTick = 0.0006f;

    // Насколько остывает симпатия за медленный тик.
    public static float WarmthDriftPerTick = 0.0002f;
}

}
