namespace HexLive.Simulation.Runtime
{

// §126: черты характера. Ручки ролла и поведения в одном месте, чтобы
// headless-харнесс мог их бисектить, а ассет TraitsBalance — крутить (§59).
//
// ⭐ Enabled = false ВЫКЛЮЧАЕТ ролл, и этого достаточно для полного отката:
// пустой набор черт — это и есть игра до §126 (каждый гейт спрашивает Has(),
// а пустая маска отвечает false), поэтому новый код остаётся на горячем пути,
// а поведение возвращается побайтово. Второй, более грубый рычаг не нужен.
//
// ⭐ Шанс 0.15 на полюс: примерно у каждой шестой девушки есть выраженная
// черта по каждой оси, а «обычный человек без особенностей» остаётся самым
// частым случаем. Полюсная пара при 0.15+0.15 оставляет 70% на «никакой».
public static class SpecTraits
{
    // Мастер-выключатель ролла (см. выше — он же и есть kill-switch фичи).
    public static bool Enabled = true;

    // ---- Рарности ролла -----------------------------------------------------
    // Полюсные пары катятся ОДНИМ хешем на пару: полоса [0, A) даёт первую
    // черту, [A, A+B) — вторую, остальное — никакой. Взаимное исключение
    // получается устройством, а не проверкой, которую можно забыть.
    // Сумма пары обязана оставаться ≤ 1.
    //
    // ⭐ АБЬЮЗЕРА И НЕРЯХИ ЗДЕСЬ НЕТ, И ЭТО НЕ ЗАБЫТЫЙ НОЛЬ. Эти две черты —
    // АВТОРСКИЕ, их носят дикари чужого клана (бутстрап + RaidWaveSystem), и в
    // нашем лагере они не заводятся вовсе. Ручка «шанс абьюзера» была бы не
    // настройкой, а дверью: поставил 0.05 — и однажды колония начала грызть
    // себя изнутри без единой строки кода. Хочешь такое — выдай черту
    // авторски, осознанно и поимённо.

    // Чистюля (§89): моется и стирает раньше остальных. Одиночная, а не полюс
    // пары, — её полюсом была бы Неряха, а неряхи в лагере не бывает.
    public static float NeatChance = 0.15f;

    // ⭐ Лентяйка / Трудяга и Трусиха / Храбрая ШИПЯТСЯ НУЛЯМИ — реализованы,
    // видны на листе, крутятся в инспекторе, но НЕ ВЫПАДАЮТ. Это не забытая
    // калибровка, а её результат: обе пары трогают выживание, и на замере
    // (24000 тиков, три сида, A/B) обе стоили колонии людей даже после
    // смягчения магнитуд — 12345: 4→4 без них против 4→2 с Лентяйкой,
    // 424242: 4→3 против 4→0 с боевой парой. Колония из четверых не имеет
    // запаса прочности на «одна работает вполсилы» и «одна лезет драться
    // подраненной»: одно решение каскадит в смерть.
    //
    // Включать их — отдельная работа со своим соаком: сначала мягким
    // параметром (лестница §62 / §29C.4A), а не поднятием шанса. Подробности и
    // цифры замера — spec.md §126.7.
    public static float LazyChance = 0f;

    public static float DiligentChance = 0f;

    public static float CowardChance = 0f;

    public static float BraveChance = 0f;

    // §49: соня.
    public static float SleepyChance = 0.15f;

    // ---- Что черта даёт ------------------------------------------------------

    // §126.4 / §49: насколько выше обычного порога соня готова лечь. Порог сна —
    // это «насколько выдохлась, чтобы лечь»: обычной хватает 0.45, соне 0.65,
    // то есть она идёт спать заметно раньше. «Спит дольше» отдельной ручки НЕ
    // требует: сон и так идёт до полной энергии (§49 NightSleepWakeEnergy), а
    // легла раньше — значит и проспала дольше.
    public static float SleepyThresholdBonus = 0.20f;

    // §126.4: во сколько раз чистюле меньше надо испачкаться, чтобы пойти
    // мыться и стирать. Множитель к порогу, а не к ставке: ставку она и так
    // потом выигрывает по общей формуле, а раньше берётся именно потому, что
    // её планка грязи ниже.
    public static float NeatThresholdMult = 0.6f;

    // §126.4: во сколько раз охотнее (трудяга) или неохотнее (лентяйка)
    // свободные руки идут в дело. Крутит прибавку freeHands у истока.
    public static float DiligentIndustryMult = 1.25f;

    public static float LazyIndustryMult = 0.8f;

    // Добавка лентяйки к ставке досуга: «меньше работает» и «больше отдыхает» —
    // разные вещи, и второй нужен свой рычаг.
    public static float LazySitBonus = 0.08f;

    // §126.4 / §62: храбрая принимает бой раньше — планка «достаточно ли она
    // цела, чтобы драться» ниже. И ВСЁ.
    //
    // ⭐ Здесь была вторая ручка — надбавка к размеру стаи, которую храбрая
    // готова встретить. Соак снял её с треском: на сиде 424242 колония с
    // чертами вымерла целиком (4→0 против 4→3 без них), и виновата была именно
    // она. Базовое AttackMaxPack = 0 читается не как «ноль храбрости», а как
    // правило «первой бьём ТОЛЬКО одиночку, лезть на стаю — самоубийство»
    // (§62), и надбавка отменяла его буквально: храбрая шла на пару волков.
    // Черта не должна уметь отменять правило выживания — только сдвигать
    // порог внутри него. 0.85 вместо 0.75 по той же причине: после первой
    // калибровки поблажка ранам осталась, но стала осторожной.
    public static float BraveFitMult = 0.85f;

    // §126.4 / §62: трусиха обходит опасность шире. Крутится СТОИМОСТЬ шага
    // внутри кольца, а не радиус кольца: кольцо считается один раз на тик и
    // общее для всех (кеш в PathfindingSystem), и персональный радиус
    // превратил бы один BFS в по одному на человека. Цена шага и так решает
    // ровно тот же вопрос — насколько широкий крюк она согласна дать.
    public static float CowardDangerCostMult = 1.5f;
}

}
