namespace HexLive.Simulation.Runtime
{

/// <summary>
/// §156: отношение системы к спящим чанкам. Объявляется каждой системой и
/// сторожится гейтом — молчаливого умолчания здесь нет, потому что «забыл
/// профильтровать» выглядит как работающий код и стоит ровно той цены, ради
/// снятия которой §156 и написан.
/// </summary>
public enum ChunkPolicy
{
    /// <summary>
    /// Мир целиком или чистая формула от тика: погода, часы, календарные
    /// прибытия, волны рейда, дневник. Чанков не касается по построению.
    /// </summary>
    Global,

    /// <summary>
    /// Работает от живых NPC и их окрестностей. Фильтровать нечего: NPC —
    /// сами драйверы пробуждения, вокруг них чанк бодр всегда.
    /// </summary>
    NpcDriven,

    /// <summary>
    /// Обходит объекты или тайлы мира и ОБЯЗАНА спрашивать
    /// <c>ChunkMath.IsAwake</c>. Это и есть системы, чья цена без §156 росла с
    /// площадью острова.
    /// </summary>
    PerChunk,
}

}
