namespace HexLive.Simulation.Runtime.Journal
{

/// <summary>
/// Spec §136: настроение, в котором сделана запись. Берётся из состояния NPC
/// В МОМЕНТ ЗАКРЫТИЯ ЧАСА, а не из типа события: одна и та же перевязка звучит
/// иначе от умирающей и от здоровой. Порядок — ПРИОРИТЕТ проверки в
/// <c>JournalMood</c>, не «сила»: сначала смертельное, потом телесное, потом
/// душевное.
/// </summary>
public enum JournalRegister : byte
{
    Plain = 0,
    Weary = 1,      // вымотана: сна нет, сил нет
    Bitter = 2,     // зло и обида: ссора, отказ, кража
    Tender = 3,     // тепло: рядом свои, о ком думать приятно
    Suffering = 4,  // больно: раны, голод, жажда
    Dying = 5       // на краю: кровопотеря, отсчёт §105
}

/// <summary>
/// Spec §136: как автор дневника относится к упомянутой в записи. Решает
/// ТЁПЛУЮ или ХОЛОДНУЮ формулировку об одном и том же поступке: «Мила меня
/// напоила, я её обожаю» против «воды мне дала — и на том спасибо».
/// </summary>
public enum JournalBond : byte
{
    Neutral = 0,
    Beloved = 1,
    Friend = 2,
    Cold = 3,
    Hated = 4
}

/// <summary>
/// Spec §136: одна запись в дневнике — ровно один игровой час.
///
/// ⭐ Здесь НЕТ и не должно быть готового текста. Запись хранит только id и
/// перечисления; фраза собирается видом из терминов I2 (§58.3), поэтому уже
/// написанный дневник целиком переезжает на другой язык по переключателю и
/// переживает переписывание формулировок без миграции сейва.
/// </summary>
public struct JournalEntry
{
    /// <summary>Тик закрытия часа — он же ключ сортировки и «прочитано до».</summary>
    public int Tick;

    /// <summary>
    /// Тип события-победителя, как в <c>GameEventTypes</c>. Пусто у тихой
    /// записи: ей нечего называть, кроме перечня бытовых дел.
    /// </summary>
    public string Type;

    public JournalRegister Register;
    public JournalBond Bond;

    /// <summary>
    /// С какой стороны автор пережил событие. «Я напоила Милу» и «Мила меня
    /// напоила» — одно событие, две записи, два разных термина.
    /// </summary>
    public JournalPerspective Perspective;

    /// <summary>
    /// Id ИМЕНИ второй участницы (<c>NPCState.DisplayName</c> — по §74 это
    /// латинский id вроде <c>jolly</c>, а не подпись). Вид превращает его в
    /// «Джоли» через <c>Loc.NpcName</c>. Пусто, если событие безличное.
    /// </summary>
    public string SubjectNameId;

    /// <summary>
    /// Третья подстановка: id предмета, конечности или зверя. Пусто, если
    /// событию нечего уточнять.
    /// </summary>
    public string Extra;

    /// <summary>
    /// Какой из вариантов фразы взять. ⭐ Считается ЧИСТЫМ хешем от
    /// (npcId, tick, type) — НЕ из мирового RNG: иначе косметическая запись
    /// перетасовала бы все броски мира и golden-trace показал бы расхождение
    /// поведения там, где поведение не менялось.
    /// </summary>
    public byte Variant;

    /// <summary>
    /// &gt;0 — это тихая запись, и столько часов подряд она покрывает. Склейка
    /// нужна, чтобы двое спокойных суток не забили кольцо сорока восемью
    /// «ничего не происходило».
    /// </summary>
    public byte QuietHours;

    /// <summary>
    /// До <c>Spec136.QuietChoreSlots</c> типов бытовых дел за эти тихие часы —
    /// то самое «пилила дрова, жгла костёр, ела мясо». Пусто у обычной записи.
    /// </summary>
    public string Chore0;
    public string Chore1;
    public string Chore2;

    public bool IsQuiet => QuietHours > 0;
}

}
