using HexLive.Simulation.Runtime;
using UnityEngine;

namespace HexLive.UnityPresentation.Config
{
    /// <summary>
    /// §126 Черты характера: КАКОЙ человек живёт в этом теле. Третий слой рядом
    /// с §76 — характеристики говорят, что тело может, навыки что руки умеют,
    /// черта что человек станет делать, когда выбор за ним. Поле ассета =
    /// camelCase одноимённого статика SpecTraits.
    ///
    /// ⭐ Черта — не фракция. До §126 «гнобит» и «не моется» были свойствами
    /// бита Faction, поэтому колонистка не могла быть неряхой, а чужак
    /// чистюлей. Теперь фракция отвечает только на «кто кому враг».
    ///
    /// ⭐ Полюсные пары (лентяйка/трудяга, трусиха/храбрая) катятся ОДНИМ
    /// броском на пару: сумма шансов пары обязана быть ≤ 1, и выпасть могут
    /// либо один полюс, либо ни одного — никогда оба.
    ///
    /// ⭐ АБЬЮЗЕРА И НЕРЯХИ ЗДЕСЬ НЕТ: это черты ДИКАРЕЙ чужого клана, они
    /// выдаются авторски при высадке, и в нашем лагере не заводятся ни при
    /// какой настройке. Ручки «шанс абьюзера» нет намеренно — она была бы не
    /// настройкой, а дверью.
    /// </summary>
    [CreateAssetMenu(menuName = "HexLive/Balance/Traits", fileName = "TraitsBalance")]
    [MirrorTarget(typeof(SpecTraits))]
    public sealed class TraitsBalanceConfig : ScriptableObject
    {
        [Header("Общее (§126)")]
        [Tooltip("Выключить — ролл черт не бросается вовсе. Пустой набор черт и есть игра до §126 байт-в-байт: каждый гейт спрашивает «есть ли черта», а пустая маска всегда отвечает «нет». Авторские черты бутстрапа (чужак) при этом остаются — они не ролл.")]
        public bool enabled = true;

        [Header("Чистюля (§89)")]
        [Tooltip("Шанс чистюли: моется и стирает раньше и охотнее обычного. ⭐ Обратного полюса (Неряха) здесь НЕТ намеренно: неряшливость — черта ДИКАРЕЙ чужого клана, она выдаётся им авторски, и в нашем лагере не заводится ни при какой настройке.")]
        [Range(0f, 1f)] public float neatChance = 0.15f;

        [Header("Лентяйка / Трудяга — ⭐ ШАНС 0: не выпадают до балансового прохода (§126.7)")]
        [Tooltip("Шанс лентяйки: свободные руки чаще уходят на досуг, чем на дела.")]
        [Range(0f, 1f)] public float lazyChance = 0f;
        [Tooltip("Шанс трудяги: свободные руки почти всегда находят работу.")]
        [Range(0f, 1f)] public float diligentChance = 0f;

        [Header("Трусиха / Храбрая (§62) — ⭐ ШАНС 0: не выпадают до балансового прохода (§126.7)")]
        [Tooltip("Шанс трусихи: обходит опасность шире и дольше, первой не нападает.")]
        [Range(0f, 1f)] public float cowardChance = 0f;
        [Tooltip("Шанс храброй: раньше принимает бой и меньше топчется в патовой.")]
        [Range(0f, 1f)] public float braveChance = 0f;

        [Header("Одиночные черты")]
        [Tooltip("Шанс сони (§49): ложится раньше. Спит всё равно до полной энергии, поэтому «дольше» выходит само.")]
        [Range(0f, 1f)] public float sleepyChance = 0.15f;

        [Header("Что черта даёт")]
        [Tooltip("§49: насколько выше обычного порога соня готова лечь. Порог сна — это «насколько выдохлась, чтобы лечь»: обычной хватает 0.45, соне 0.65. Отдельной ручки на «спит дольше» нет и не нужно: сон и так идёт до полной энергии.")]
        [Range(0f, 0.5f)] public float sleepyThresholdBonus = 0.20f;
        [Tooltip("§89: во сколько раз чистюле меньше надо испачкаться, чтобы пойти мыться и стирать. Множитель к ПОРОГУ, а не к ставке: раньше берётся именно потому, что её планка грязи ниже.")]
        [Range(0.2f, 1f)] public float neatThresholdMult = 0.6f;
        [Tooltip("Во сколько раз охотнее трудяга берётся за дело, когда руки свободны. Крутит одну прибавку у истока — она кормит все хозяйственные ставки разом.")]
        [Range(1f, 3f)] public float diligentIndustryMult = 1.25f;
        [Tooltip("То же для лентяйки, в обратную сторону.")]
        [Range(0.1f, 1f)] public float lazyIndustryMult = 0.8f;
        [Tooltip("Добавка лентяйки к желанию посидеть. Отдельно от множителя работы: «меньше работает» и «больше отдыхает» — разные вещи, и человеку надо куда-то деваться вместо дела.")]
        [Range(0f, 0.5f)] public float lazySitBonus = 0.08f;
        [Tooltip("§62: во сколько раз ниже планка «достаточно цела, чтобы драться первой» у храброй. ⭐ Ручки «на сколько больше зверей она встретит» здесь НЕТ и быть не должно: «первой бьём только одиночку, стая — самоубийство» это правило выживания §62, и черта его не отменяет. Соак, где отменяла, стоил колонии всех четверых.")]
        [Range(0.3f, 1f)] public float braveFitMult = 0.85f;
        [Tooltip("§62: во сколько раз дороже трусихе шаг рядом со зверем — то есть насколько шире крюк она даёт. Крутится ЦЕНА шага, а не радиус кольца: кольцо считается одним обходом на тик и общее для всех.")]
        [Range(1f, 5f)] public float cowardDangerCostMult = 1.5f;
    }
}
