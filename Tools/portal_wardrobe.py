"""Generate the portal wardrobe allowlist from the player-reviewed Modern catalog."""

import argparse
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
WARDROBE = ROOT / "Assets/HexLiveContent/People/Wardrobe"
OUTPUT = ROOT / "Assets/HexLive/Simulation/Content/PortalWardrobeCatalog.cs"
CONTENT_ID = re.compile(r"[a-z0-9][a-z0-9_.-]*")

# Model families cover all their color variants. Civilian sports and workwear
# remain available. Uniforms, combat gear and costume armor stay staged.
# PortalContentPolicy.NonCivilianModels (C#) repeats this list (plus the
# island-only FCO Gloves Male) for the live island garments that also stock
# the apartment wardrobe (bug #743). Edit both together.
NON_CIVILIAN = {
    "FAO Harness Male", "FCO Belt Male", "FCO Boots Male", "FCO Knee Straps Male",
    "FCO Legs Straps Male", "FCO Pants Male", "FCO Waist Strappy Male", "TonnyFlash",
    "clothing.belt_holster", "clothing.belt_stars", "clothing.boots_alloy",
    "clothing.boots_osiris", "clothing.cap_stars", "clothing.greaves_tod",
    "clothing.helmet_knight", "clothing.helmet_m1", "clothing.helmet_space",
    "clothing.helmet_tactical", "clothing.helmet_tactical_headset", "clothing.helmet_vietnam",
    "clothing.jacket_ranger", "clothing.pants_ranger", "clothing.pants_stars",
    "clothing.shorts_osiris", "clothing.top_alloy", "clothing.top_osiris", "clothing.top_stars",
    "clothing.vest_ranger", "gear.backpack_osiris", "gear.beltpouch_ranger",
}


def load(name):
    return json.loads((WARDROBE / name).read_text(encoding="utf-8-sig"))


def owners():
    catalog = load("release-catalog.json")
    fit = load("release-fit.json")
    if catalog["contentOrigin"] != "modern" or not fit["passed"]:
        raise ValueError("The reviewed Modern catalog and successful fit are required")

    catalog_records = catalog["records"]
    wear = []
    used_prefabs = set()
    for record in catalog_records:
        if record["type"] != "wear":
            continue
        metadata = record["metadata"]
        model = metadata["simulation"]["prototypeId"]
        if model in NON_CIVILIAN or record["id"] in NON_CIVILIAN:
            continue
        if not CONTENT_ID.fullmatch(record["id"]) or metadata.get("finalFit") is not True:
            raise ValueError(f"Invalid civilian wear owner {record['id']}")
        wear.append(record["id"])
        used_prefabs.add(record["main"])

    verified_fits = {row["final"]["prefab"]: row["final"] for row in fit["rows"].values() if row.get("final")}
    paths = {item["path"] for prefab in used_prefabs for item in verified_fits[prefab]["maps"]}
    maps = {record["main"]: record["id"] for record in catalog_records if record["type"] == "config"}
    if not paths <= maps.keys():
        raise ValueError("A civilian garment is missing its fitted paint maps")
    return sorted(wear), sorted(maps[path] for path in paths)


def render(wear, maps):
    def entries(ids):
        return "\n".join(f'        "{identifier}",' for identifier in ids)

    return f"""// Generated by Tools/portal_wardrobe.py from the reviewed Modern catalog.
using System;
using System.Collections.Generic;

namespace HexLive.Simulation.Content
{{

internal static class PortalWardrobeCatalog
{{
    internal static IReadOnlyList<string> Wear {{ get; }} = Array.AsReadOnly(new[]
    {{
{entries(wear)}
    }});

    internal static IReadOnlyList<string> PaintMaps {{ get; }} = Array.AsReadOnly(new[]
    {{
{entries(maps)}
    }});
}}

}}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    wear, maps = owners()
    source = render(wear, maps)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != source:
            raise SystemExit("Run Tools/portal_wardrobe.py to update the portal wardrobe allowlist")
    else:
        OUTPUT.write_text(source, encoding="utf-8", newline="\n")
    print(f"Portal wardrobe: {len(wear)} civilian wear owners and {len(maps)} paint-map owners")


if __name__ == "__main__":
    main()
